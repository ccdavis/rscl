;; Destructuring in let, fn, defn, loop and doseq.
(let [[a b & more :as all] [1 2 3 4 5]] (println a b more all))
(let [[a [b [c]] d] [1 [2 [3]] 4]] (println a b c d))
(let [[a b] [1]] (println a b))
(let [{:keys [x y] :or {y 10} :as m} {:x 1}] (println x y m))
(let [{:keys [a/b c]} {:a/b 1 :c 2}] (println b c))
(let [{:strs [s] :syms [y] v :k} {"s" 1 'y 2 :k 3}] (println s y v))
(let [{[a b] :pair {c :c} :nested} {:pair [1 2] :nested {:c 3}}] (println a b c))
(defn sum-pair [[a b]] (+ a b))
(defn greet [{:keys [name greeting] :or {greeting "Hello"}}] (str greeting ", " name))
(println (sum-pair [1 2]) (greet {:name "Ada"}) (greet {:name "Bob" :greeting "Hi"}))
(defn multi
  ([[a]] (str "one:" a))
  ([[a] {:keys [b]}] (str "two:" a b)))
(println (multi [1]) (multi [1] {:b 2}))
(defn rest-destructure [x & [y z]] [x y z])
(println (rest-destructure 1) (rest-destructure 1 2 3))
(println (loop [[x & xs] [1 2 3] acc []] (if x (recur xs (conj acc (* x x))) acc)))
(doseq [[k v] {:a 1 :b 2}] (println k v))
(doseq [{:keys [n]} [{:n 1} {:n 2}] :let [m (* n 10)] :when (> m 10)] (println n m))
(println (for [[k v] {:a 1 :b 2}] (str k "=" v)))
