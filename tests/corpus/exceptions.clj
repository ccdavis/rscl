;; throw / try / catch / finally, ex-info, and cleanup on exceptional paths.
(println (try (/ 1 0) (catch ArithmeticException e (str "caught: " (ex-message e)))))
(println (try (+ 1 nil) (catch Exception e :any)))
(println (try (throw (ex-info "boom" {:code 7})) (catch ExceptionInfo e [(ex-message e) (ex-data e)])))
(println (try (throw (ex-info "boom" {})) (catch ArithmeticException e :wrong) (catch Throwable e :right)))
(println (try 1 (finally (println "finally runs"))))
(println (try (throw (ex-info "x" {})) (catch Exception e :caught) (finally (println "finally after catch"))))
(defn risky [x] (if (neg? x) (throw (ex-info "negative" {:x x})) (* x 2)))
(println (map (fn [x] (try (risky x) (catch Exception e (:x (ex-data e))))) [1 -2 3]))
(println (try (try (throw (ex-info "inner" {})) (finally (println "inner finally"))) (catch Exception e (str "outer caught " (ex-message e)))))
(println (try (try (throw (ex-info "a" {})) (catch Exception e (throw (ex-info (str (ex-message e) "b") {})))) (catch Exception e (ex-message e))))
(println (let [s (str "owned" "-string")] (try (+ s 1) (catch ClassCastException e (str s " kept")))))
(println (loop [i 0 acc []] (if (< i 3) (recur (inc i) (conj acc (try (if (= i 1) (throw (ex-info "one" {})) i) (catch Exception e :e)))) acc)))
(println (try (throw 42) (catch Throwable e (str "thrown value " e))))
(println (ex-message (try (nth [1] 5) (catch Exception e e))))
(println (try (do (println "body") :done) (catch Exception e :no) (finally (println "cleanup"))))
(defn with-finally [f] (try (f) (finally (println "always"))))
(println (with-finally (fn [] :ok)))
(println (try (with-finally (fn [] (throw (ex-info "late" {})))) (catch Exception e (ex-message e))))
